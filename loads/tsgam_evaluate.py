def partition_datetime_index_weeks(
    dt_index: pd.DatetimeIndex,
    n_weeks: int = 1,
) -> Tuple[pd.DatetimeIndex, pd.DatetimeIndex]:
    """
    Partition a datetime index into training and test sets.
    
    Holds out N evenly-spaced weeks throughout the year for testing.
    The weeks are distributed to maximize spacing across the year.
    
    Parameters
    ----------
    dt_index : pd.DatetimeIndex
        The datetime index to partition (can be tz-aware or tz-naive)
    n_weeks : int, default=1
        Number of weeks to hold out for testing. These weeks will be
        evenly distributed throughout the year. If n_weeks=1, the last
        week is held out. If n_weeks=2, weeks 26 and 52 are held out, etc.
        
    Returns
    -------
    Tuple[pd.DatetimeIndex, pd.DatetimeIndex]
        A tuple of (training_index, test_index)
        
    Examples
    --------
    >>> idx = pd.date_range('2023-01-01', '2023-12-31', freq='D')
    >>> train_idx, test_idx = partition_datetime_index_weeks(idx, n_weeks=2)
    >>> len(train_idx) + len(test_idx) == len(idx)
    True
    
    Notes
    -----
    - Week numbers are based on ISO 8601 week-numbering year (1-52 or 1-53)
    - For N weeks, the weeks are selected as: 52, 52-52/N, 52-2*52/N, ...
    - This ensures even spacing with the last week always included
    """
    if n_weeks < 1:
        raise ValueError("n_weeks must be at least 1")
    
    if n_weeks > 52:
        raise ValueError("n_weeks cannot exceed 52 (weeks in a year)")
    
    # Calculate which week numbers to hold out
    # We want to evenly space N weeks across 52 weeks, always including week 52
    if n_weeks == 1:
        test_weeks = {52}
    else:
        # Space weeks evenly: 52, 52-52/N, 52-2*52/N, etc.
        spacing = 52 / n_weeks
        test_weeks = set()
        for i in range(n_weeks):
            week_num = int(round(52 - i * spacing))
            # Ensure week number is valid (1-53)
            week_num = max(1, min(53, week_num))
            test_weeks.add(week_num)
    
    # Create boolean mask for test dates
    is_test = pd.Series(False, index=range(len(dt_index)))
    
    for i, dt in enumerate(dt_index):
        # Get ISO week number (1-52 or 1-53)
        week_num = dt.isocalendar()[1]
        
        # Get ISO year (may differ from calendar year for dates near year boundary)
        iso_year = dt.isocalendar()[0]
        
        # Check if this week number is in our test set
        # We need to check for each ISO year separately to handle multi-year indices
        if week_num in test_weeks:
            is_test.iloc[i] = True
    
    test_index = dt_index[is_test.values]
    train_index = dt_index[~is_test.values]
    return train_index,test_index

def predict(
    X:pd.DataFrame,
    y:np.array,
    training:pd.DatetimeIndex,
    year_harmonics:int,
    week_harmonics:int,
    day_harmonics:int,
    n_knots:int,
    lag_size:int,
    *,
    verbose:bool=False,
    random_state:float|None=None,
    debug:bool=False,
    ):
    """Construct estimator from config parameters and predict data"""
    config = TsgamEstimatorConfig(
        multi_periodic_config=TsgamMultiPeriodicConfig(
            num_harmonics=[year_harmonics, week_harmonics, day_harmonics],
            periods=[365.2425 * 24, 7 * 24, 24]
        ),
        exog_config=[TsgamSplineConfig(
                    knots=[],  # Empty list means knots will be auto-generated from data
                    n_knots=n_knots,  # Number of knots to generate
                    lags=list(range(-lag_size,lag_size+1)),
                    reg_weight=1e-4,  # Regularization weight for coefficients
                    diff_reg_weight=1.0  # Regularization weight for differences between lags
                )],
        ar_config=None,
        solver_config=TsgamSolverConfig(
            solver='CLARABEL',
            verbose=verbose
        ),
        random_state=random_state,
        debug=debug
    )

    scale = y.max()
    estimator = TsgamEstimator(config=config)
    estimator.fit(X.loc[training],y.loc[training].values / scale)

    # get the test data
    return estimator.predict(X) * scale

def evaluate(actuals,values,ndx):
    """Evaluate rmse of data columns over specified index"""
    return np.sqrt(((actuals.loc[ndx] - values.loc[ndx])**2).mean())

