    """Find best training configuration among choices of configuration"""

    found = False
    for choice in choices if best is None else [best]+choices:

        try:
            try:
                rmse,values = CACHE[str(choice)]
            except KeyError:
                tic = time()
                values = pd.DataFrame({"predict":predict(X,y,training,*choice)},index=X.index)
                rmse = evaluate(y,values["predict"],testing).round(2)
                CACHE[str(choice)] = (rmse,values)
                print(*choice,f"{rmse:.2f},{time()-tic:.3f}",flush=True,sep=",")
            if best is None or rmse < ref:
                found = True
                best = choice
                result = values
                ref = rmse
        except Exception as err:
            print("EXCEPTION",err,sep=",")
    if not found:
        raise RuntimeError("already optimal")
    return best,result,ref

