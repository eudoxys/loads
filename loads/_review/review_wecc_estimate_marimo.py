"""WECC county load estimate

This [marimo](https://marimo.io/) notebook displays the hourly county load
estimates in `loads/wecc/wecc_estimate.csv.gz` generated by
`loads/wecc/wecc_estimate.py`.

Select a state and a county to view the county's hourly load (MW) from
2018-01-01 00:00 UTC through 2022-12-31 23:00 UTC, one day per page.
"""

import marimo

__generated_with = "0.25.0"
app = marimo.App(width="medium", app_title="WECC County Load Estimate")


@app.cell
def _(mo):
    mo.md(f"""
    ## {__doc__}
    """)
    return


@app.cell
def _(mo, pathlib, pd):
    # load the estimate
    _file = pathlib.Path(*pathlib.Path(__file__).parts[:-2],"wecc","wecc_estimate.csv.gz")
    mo.stop(not _file.exists(),
        mo.md(f"**{_file.name}** not found. Run `python3 wecc_estimate.py` in `loads/wecc` first."))
    with mo.status.spinner("Loading WECC estimate"):
        data = pd.read_csv(_file,index_col=[0],parse_dates=[0])
    return (data,)


@app.cell
def _(data, mo):
    # state selection
    _options = sorted({x.rsplit("_",1)[1] for x in data.columns})
    state_ui = mo.ui.dropdown(options=_options,value=_options[0],label="State:")
    return (state_ui,)


@app.cell
def _(data, mo, state_ui):
    # county selection
    _options = sorted(x.rsplit("_",1)[0] for x in data.columns if x.endswith(f"_{state_ui.value}"))
    county_ui = mo.ui.dropdown(options=_options,value=None,label="County:")
    return (county_ui,)


@app.cell
def _(county_ui, mo, state_ui):
    mo.hstack([state_ui,county_ui],justify="start")
    return


@app.cell
def _(county_ui, data, mo, state_ui):
    # county data
    if county_ui.value is None:
        _columns = [x for x in data.columns if x.endswith(state_ui.value)]
    else:
        _columns = [f"{county_ui.value}_{state_ui.value}"]
    mo.ui.table(data[_columns],page_size=24,selection=None)
    return


@app.cell
def _():
    import marimo as mo
    import pathlib
    import pandas as pd

    return mo, pathlib, pd


if __name__ == "__main__":
    app.run()
