"""WECC240 node uncalibrated load estimate

This [marimo](https://marimo.io/) notebook displays the hourly node load
estimates in `loads/wecc/node_estimate_total.csv.gz` generated by
`loads/wecc/node_estimate.py` from `loads/wecc/wecc_total_estimate.csv.gz`.

Select a state to view the total load of its nodes, or no state to view the
total load of all WECC240 nodes. Select a node to view that node only, and
the counties that contribute to it. Select a year to view that year only, or
no year to view 2018 through 2022, and a month to view that month of the
selected year only.

Each node is placed in the state of its busses (`wecc240` `bus_gis.csv`).
The nodes outside the US are listed under `Canada` and `Mexico`.
"""

import marimo

__generated_with = "0.25.0"
app = marimo.App(width="medium", app_title="WECC240 Node Uncalibrated Load Estimate")


@app.cell
def _(mo):
    mo.md(f"""
    ## {__doc__}
    """)
    return


@app.cell
def _(importlib, mo, pathlib, pd):
    # load the node estimate, contribution factors and node_estimate settings
    _folder = pathlib.Path(__file__).parent
    _file = _folder / "node_estimate_total.csv.gz"
    mo.stop(not _file.exists(),
        mo.md(f"**{_file.name}** not found. Run"
            " `python3 node_estimate.py -i wecc_total_estimate.csv.gz -o node_estimate_total.csv.gz`"
            " in `loads/wecc` first."))
    with mo.status.spinner("Loading node total estimate"):
        data = pd.read_csv(_file,index_col=[0],parse_dates=[0])
        cf = pd.read_csv(_folder / "node_estimate_cf.csv")
    _spec = importlib.util.spec_from_file_location("node_estimate",_folder / "node_estimate.py")
    node_estimate = importlib.util.module_from_spec(_spec)
    _spec.loader.exec_module(node_estimate)
    return cf, data, node_estimate


@app.cell
def _(data, mo, node_estimate, os, pd):
    # node state and name from the wecc240 busses (sibling clone, otherwise GitHub)
    _folder = node_estimate.WECC240_LOCAL if os.path.exists(node_estimate.WECC240_LOCAL) \
        else node_estimate.WECC240_URL
    def _wecc240(name):
        return f"{_folder}/data/{name}" if "://" in _folder else os.path.join(_folder,"data",name)
    with mo.status.spinner("Loading wecc240 busses"):
        _bus = pd.read_csv(_wecc240("bus_gis.csv"),dtype={"FIPS":str})
        _counties = pd.read_csv(_wecc240("counties.csv"),dtype={"FIPS":str})
    _bus["ST"] = _bus["FIPS"].map(_counties.set_index("FIPS")["ST"])
    _bus = _bus[_bus["GEOHASH"].isin(data.columns)]
    nodes = pd.DataFrame({
        "state":_bus.dropna(subset="ST").groupby("GEOHASH")["ST"].agg(lambda x: x.mode()[0]),
        "name":_bus.groupby("GEOHASH")["NAME"].first(),
        }).reindex(data.columns)
    for _node,_country in node_estimate.FOREIGN.items():
        if _node in nodes.index:
            nodes.loc[_node,"state"] = _country
    nodes["state"] = nodes["state"].fillna("Unknown")
    return (nodes,)


@app.cell
def _(data, mo, nodes):
    # state and year selection
    _states = sorted(nodes["state"].unique())
    state_ui = mo.ui.dropdown(options=_states,value=None,allow_select_none=True,
        label="State:")
    _years = sorted({str(x.year) for x in data.index})
    year_ui = mo.ui.dropdown(options=_years,value=None,allow_select_none=True,
        label="Year:")
    return state_ui, year_ui


@app.cell
def _(mo, nodes, state_ui):
    # node selection (only when a state is selected)
    _nodes = nodes[nodes["state"]==state_ui.value].sort_values(["name"])
    node_ui = mo.ui.dropdown(
        options={f"{x} ({y})" if isinstance(y,str) else x:x for x,y in _nodes["name"].items()},
        value=None,allow_select_none=True,label="Node:",disabled=state_ui.value is None)
    return (node_ui,)


@app.cell
def _(calendar, mo, year_ui):
    # month selection (only when a year is selected)
    month_ui = mo.ui.dropdown(options={calendar.month_name[x]:x for x in range(1,13)},
        value=None,allow_select_none=True,label="Month:",disabled=year_ui.value is None)
    return (month_ui,)


@app.cell
def _(mo, month_ui, node_ui, state_ui, year_ui):
    mo.hstack([state_ui,node_ui,year_ui,month_ui],justify="start")
    return


@app.cell
def _(calendar, data, month_ui, node_ui, nodes, state_ui, year_ui):
    # selected nodes and period
    if state_ui.value is None:
        columns = list(data.columns)
        area = "WECC"
    elif node_ui.value is None:
        columns = list(nodes.index[nodes["state"]==state_ui.value])
        area = state_ui.value
    else:
        columns = [node_ui.value]
        _name = nodes.loc[node_ui.value,"name"]
        area = f"Node {node_ui.value}" + (f" ({_name})" if isinstance(_name,str) else "")

    if year_ui.value is None:
        selected = data[columns]
        period = f"{data.index[0]:%Y-%m-%d} to {data.index[-1]:%Y-%m-%d}"
    elif month_ui.value is None:
        selected = data.loc[year_ui.value,columns]
        period = year_ui.value
    else:
        selected = data.loc[f"{year_ui.value}-{month_ui.value:02d}",columns]
        period = f"{calendar.month_name[month_ui.value]} {year_ui.value}"

    total = selected.sum(axis=1,min_count=1)
    return area, columns, period, selected, total


@app.cell
def _(area, columns, mo, period, total):
    # summary
    _hours = total.count()
    mo.stop(_hours == 0,mo.md(f"**No data for {area} in {period}.**"))
    mo.hstack([
        mo.stat(f"{len(columns)}",label="Nodes"),
        mo.stat(f"{total.max():,.0f} MW",label="Peak",caption=f"{total.idxmax():%Y-%m-%d %H:%M} UTC"),
        mo.stat(f"{total.min():,.0f} MW",label="Minimum",caption=f"{total.idxmin():%Y-%m-%d %H:%M} UTC"),
        mo.stat(f"{total.mean():,.0f} MW",label="Mean",caption=f"{_hours:,} hours"),
        mo.stat(f"{total.sum()/1e3:,.0f} GWh",label="Energy"),
        ],justify="start")
    return


@app.cell
def _(area, period, plt, total):
    # hourly load plot
    plt.close()
    _fig,_ax = plt.subplots(figsize=(10,4))
    total.plot(ax=_ax,linewidth=0.5)
    _ax.set_ylabel("Load (MW)")
    _ax.set_xlabel("Date/Time (UTC)")
    _ax.set_title(f"{area} uncalibrated load estimate, {period}")
    _ax.grid(alpha=0.3)
    _fig
    return


@app.cell
def _(columns, mo, nodes, selected, state_ui, total):
    # hourly data: by state for WECC, by node for a state, the node otherwise
    if state_ui.value is None:
        _table = selected.T.groupby(nodes["state"]).sum(min_count=1).T
    else:
        _table = selected.copy()
    if len(columns) > 1:
        _table.insert(0,"Total",total)
    mo.ui.table(_table.round(1),page_size=24,selection=None)
    return


@app.cell
def _(cf, mo, node_estimate, node_ui):
    # counties contributing to the selected node
    mo.stop(node_ui.value is None)
    _counties = cf[cf["node"]==node_ui.value][["county_st","cf","method"]].round({"cf":4})
    _foreign = node_estimate.FOREIGN.get(node_ui.value)
    _note = (f"  \nIncludes the {_foreign} load from `wecc240` `{_foreign}/{node_ui.value}.csv`."
        if _foreign else "")
    mo.vstack([
        mo.md(f"**Counties contributing to node {node_ui.value}**{_note}"),
        mo.ui.table(_counties.reset_index(drop=True),selection=None)
            if len(_counties) else mo.md("No counties."),
    ])
    return


@app.cell
def _():
    import marimo as mo
    import os
    import pathlib
    import calendar
    import importlib.util
    import pandas as pd
    import matplotlib.pyplot as plt

    return calendar, importlib, mo, os, pathlib, pd, plt


if __name__ == "__main__":
    app.run()
