"""WECC county uncalibrated load estimate

This [marimo](https://marimo.io/) notebook displays the hourly county load
estimates in `loads/wecc/wecc_total_estimate.csv.gz` generated by
`loads/wecc/wecc_total_estimate.py`.

Select a state to view the total load of its counties, or no state to view
the total load of all WECC counties. Select a county to view that county
only. Select a year to view that year only, or no year to view 2018 through
2022, and a month to view that month of the selected year only.
"""

import marimo

__generated_with = "0.25.0"
app = marimo.App(width="medium", app_title="WECC County Uncalibrated Load Estimate")


@app.cell
def _(mo):
    mo.md(f"""
    ## {__doc__}
    """)
    return


@app.cell
def _(mo, pathlib, pd):
    # load the estimate
    _file = pathlib.Path(__file__).parent / "wecc_total_estimate.csv.gz"
    mo.stop(not _file.exists(),
        mo.md(f"**{_file.name}** not found. Run `python3 wecc_total_estimate.py` in `loads/wecc` first."))
    with mo.status.spinner("Loading WECC total estimate"):
        data = pd.read_csv(_file,index_col=[0],parse_dates=[0])
    return (data,)


@app.cell
def _(data, mo):
    # state and year selection
    _states = sorted({x.rsplit(" ",1)[1] for x in data.columns})
    state_ui = mo.ui.dropdown(options=_states,value=None,allow_select_none=True,
        label="State:")
    _years = sorted({str(x.year) for x in data.index})
    year_ui = mo.ui.dropdown(options=_years,value=None,allow_select_none=True,
        label="Year:")
    return state_ui, year_ui


@app.cell
def _(data, mo, state_ui):
    # county selection (only when a state is selected)
    _counties = sorted(x.rsplit(" ",1)[0] for x in data.columns
        if state_ui.value and x.endswith(f" {state_ui.value}"))
    county_ui = mo.ui.dropdown(options=_counties,value=None,allow_select_none=True,
        label="County:",disabled=state_ui.value is None)
    return (county_ui,)


@app.cell
def _(calendar, mo, year_ui):
    # month selection (only when a year is selected)
    month_ui = mo.ui.dropdown(options={calendar.month_name[x]:x for x in range(1,13)},
        value=None,allow_select_none=True,label="Month:",disabled=year_ui.value is None)
    return (month_ui,)


@app.cell
def _(county_ui, mo, month_ui, state_ui, year_ui):
    mo.hstack([state_ui,county_ui,year_ui,month_ui],justify="start")
    return


@app.cell
def _(calendar, county_ui, data, month_ui, state_ui, year_ui):
    # selected counties and period
    if state_ui.value is None:
        columns = list(data.columns)
        area = "WECC"
    elif county_ui.value is None:
        columns = [x for x in data.columns if x.endswith(f" {state_ui.value}")]
        area = state_ui.value
    else:
        columns = [f"{county_ui.value} {state_ui.value}"]
        area = columns[0]

    if year_ui.value is None:
        selected = data[columns]
        period = f"{data.index[0]:%Y-%m-%d} to {data.index[-1]:%Y-%m-%d}"
    elif month_ui.value is None:
        selected = data.loc[year_ui.value,columns]
        period = year_ui.value
    else:
        selected = data.loc[f"{year_ui.value}-{month_ui.value:02d}",columns]
        period = f"{calendar.month_name[month_ui.value]} {year_ui.value}"

    total = selected.sum(axis=1,min_count=1)
    return area, columns, period, selected, total


@app.cell
def _(area, columns, mo, period, total):
    # summary
    _hours = total.count()
    mo.stop(_hours == 0,mo.md(f"**No data for {area} in {period}.**"))
    mo.hstack([
        mo.stat(f"{len(columns)}",label="Counties"),
        mo.stat(f"{total.max():,.0f} MW",label="Peak",caption=f"{total.idxmax():%Y-%m-%d %H:%M} UTC"),
        mo.stat(f"{total.min():,.0f} MW",label="Minimum",caption=f"{total.idxmin():%Y-%m-%d %H:%M} UTC"),
        mo.stat(f"{total.mean():,.0f} MW",label="Mean",caption=f"{_hours:,} hours"),
        mo.stat(f"{total.sum()/1e3:,.0f} GWh",label="Energy"),
        ],justify="start")
    return


@app.cell
def _(area, period, plt, total):
    # hourly load plot
    plt.close()
    _fig,_ax = plt.subplots(figsize=(10,4))
    total.plot(ax=_ax,linewidth=0.5)
    _ax.set_ylabel("Load (MW)")
    _ax.set_xlabel("Date/Time (UTC)")
    _ax.set_title(f"{area} uncalibrated load estimate, {period}")
    _ax.grid(alpha=0.3)
    _fig
    return


@app.cell
def _(columns, mo, selected, state_ui, total):
    # hourly data: by state for WECC, by county for a state, the county otherwise
    if state_ui.value is None:
        _table = selected.T.groupby(lambda x: x.rsplit(" ",1)[1]).sum(min_count=1).T
    else:
        _table = selected.copy()
    if len(columns) > 1:
        _table.insert(0,"Total",total)
    mo.ui.table(_table.round(1),page_size=24,selection=None)
    return


@app.cell
def _():
    import marimo as mo
    import pathlib
    import calendar
    import pandas as pd
    import matplotlib.pyplot as plt

    return calendar, mo, pathlib, pd, plt


if __name__ == "__main__":
    app.run()
